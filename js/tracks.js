// Circuitos incluidos: una vuelta al mundo con cuatro circuitos por continente. Son grandes (vueltas
// de 1,15 a 1,55 km) y de formas variadas: contornos en L, U o escalera, manchas alargadas y ochos
// con puente; cada uno gira en un sentido y sale desde un punto distinto. Curvas largas y abiertas
// con dos o tres cerradas por vuelta; en la pista solo hay barro, charcos y algún salto natural en
// las rectas. Los objetos se colocan con f (fracción del recorrido, 0–1) y o (desplazamiento lateral
// en px); resolveDef() los convierte.
import { DEFAULT_W } from './config.js';

const SURF_CODE = { a: 'asfalto', t: 'tierra', n: 'nieve' };

function mkTrack(name, type, laps, theme, pts, objs, patches) {
  return {
    name, type, laps, theme,
    pts: pts.map(([x, y, s, w]) => ({ x, y, s: SURF_CODE[s], w: w || DEFAULT_W[SURF_CODE[s]] })),
    objs, patches,
  };
}

